/**
 * Текущее время сервера — для синхронизации клиентских часов (server-clock).
 *
 * Зачем: таймеры Выживания и Блица считают по часам устройства, а сервер —
 * по своим. Часы телефона, спешащие на 2 с, обрывали волну раньше банка и
 * показывали «следующую волну» с остатком в 1 с (прод, окт 2026). Клиент
 * делает пару запросов сюда и по времени ответа вычисляет поправку.
 *
 * Без БД и auth: ответ за доли миллисекунды, не будит Neon, не трогает
 * горячий путь квиза. Время не секрет.
 */

import { NextResponse } from 'next/server';

export const dynamic = 'force-dynamic';

export function GET() {
    return NextResponse.json(
        { now: Date.now() },
        { headers: { 'Cache-Control': 'no-store' } },
    );
}
